// ========================================
// ACAK
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[Math.floor(Math.random() * data.length)];

}


// ========================================
// COPY TEXT
// ========================================

async function copyTeks(text, button) {

    if (!text) return;

    try {

        await navigator.clipboard.writeText(text);

        if (button) {

            const oldText = button.innerHTML;

            button.innerHTML = "COPIED ✔";

            setTimeout(() => {
                button.innerHTML = oldText;
            }, 1500);

        }

    } catch (error) {

        console.error("COPY TEXT GAGAL:", error);

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game = dataGame[id];

    if (!game) return;

    copyTeks(
        ambilAcak(game.saran),
        button
    );

}


// ========================================
// COPY FOTO GAME
// ========================================

async function copyFotoGame(img, button) {

    if (!img || !img.complete || img.naturalWidth === 0) {

        console.error("❌ FOTO BELUM SIAP");

        if (button) {
            button.innerHTML = "⏳ FOTO BELUM SIAP";

            setTimeout(() => {
                button.innerHTML = "🔥 POLA GAME";
            }, 1500);
        }

        return;
    }

    if (
        !navigator.clipboard ||
        typeof ClipboardItem === "undefined"
    ) {

        console.error("❌ BROWSER TIDAK SUPPORT COPY FOTO");

        if (button) {
            button.innerHTML = "❌ TIDAK DIDUKUNG";
        }

        return;
    }

    button.disabled = true;
    button.innerHTML = "⏳ MENYALIN FOTO...";

    try {

        const url = img.currentSrc || img.src;

        const response = await fetch(url, {
            cache: "no-cache"
        });

        if (!response.ok) {
            throw new Error("HTTP " + response.status);
        }

        const blob = await response.blob();

        const bitmap = await createImageBitmap(blob);

        const canvas = document.createElement("canvas");

        canvas.width = bitmap.width;
        canvas.height = bitmap.height;

        const ctx = canvas.getContext("2d");

        ctx.drawImage(bitmap, 0, 0);

        bitmap.close();

        const pngBlob = await new Promise((resolve, reject) => {

            canvas.toBlob((hasil) => {

                if (hasil) {
                    resolve(hasil);
                } else {
                    reject(new Error("Gagal membuat PNG"));
                }

            }, "image/png");

        });

        await navigator.clipboard.write([
            new ClipboardItem({
                "image/png": pngBlob
            })
        ]);

        console.log("✅ FOTO BERHASIL DICOPY");

        button.innerHTML = "📸 FOTO COPIED ✔";

        setTimeout(() => {

            button.innerHTML = "🔥 POLA GAME";
            button.disabled = false;

        }, 1800);

    } catch (error) {

        console.error("❌ COPY FOTO GAGAL:", error);

        button.innerHTML = "❌ COPY FOTO GAGAL";

        setTimeout(() => {

            button.innerHTML = "🔥 POLA GAME";
            button.disabled = false;

        }, 2000);

    }

}


// ========================================
// POLA GAME
// KLIK = COPY FOTO
// ========================================

function polaGame(id, button) {

    const gameBox = button.closest(".game-box");

    if (!gameBox) return;

    const img = gameBox.querySelector(".game-image");

    if (!img) return;

    copyFotoGame(img, button);

}


// ========================================
// CARI FOTO
// ========================================

function cariFoto(i, img) {

    const daftarFoto = [

        `./game${i}.jpg`,
        `./game${i}.jpeg`,
        `./game${i}.png`,
        `./game${i}.webp`,

        `./Game${i}.jpg`,
        `./Game${i}.jpeg`,
        `./Game${i}.png`,
        `./Game${i}.webp`,

        `./GAME${i}.jpg`,
        `./GAME${i}.jpeg`,
        `./GAME${i}.png`,
        `./GAME${i}.webp`

    ];

    let index = 0;

    function cobaFoto() {

        if (index >= daftarFoto.length) {

            console.error(
                `❌ FOTO GAME ${i} TIDAK DITEMUKAN`
            );

            img.removeAttribute("src");

            return;
        }

        const path = daftarFoto[index];

        img.onload = function () {

            console.log(
                `✅ FOTO ${i} BERHASIL: ${path}`
            );

        };

        img.onerror = function () {

            index++;

            cobaFoto();

        };

        img.src = path;

    }

    cobaFoto();

}


