// ========================================
// ACAK
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[Math.floor(Math.random() * data.length)];

}


// ========================================
// COPY TEXT
// ========================================

async function copyTeks(text, button) {

    if (!text) return;

    try {

        await navigator.clipboard.writeText(text);

        if (button) {

            const oldText = button.innerHTML;

            button.innerHTML = "COPIED ✔";

            setTimeout(() => {

                button.innerHTML = oldText;

            }, 800);

        }

    } catch (error) {

        console.error("COPY TEXT GAGAL:", error);

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game = dataGame[id];

    if (!game) return;

    copyTeks(
        ambilAcak(game.saran),
        button
    );

}


// ========================================
// CACHE FOTO
// ========================================

const fotoCache = {};


// ========================================
// SIAPKAN FOTO
// ========================================

function siapkanFoto(img, id) {

    if (!img || !img.complete || !img.naturalWidth) {
        return;
    }

    if (fotoCache[id]) {
        return;
    }

    try {

        const canvas =
            document.createElement("canvas");

        canvas.width =
            img.naturalWidth;

        canvas.height =
            img.naturalHeight;

        const ctx =
            canvas.getContext("2d");

        ctx.drawImage(
            img,
            0,
            0
        );

        canvas.toBlob(
            function (blob) {

                if (blob) {

                    fotoCache[id] = blob;

                    console.log(
                        "📸 FOTO " + id + " SIAP"
                    );

                }

            },
            "image/png"
        );

    } catch (error) {

        console.error(
            "❌ CACHE FOTO GAGAL:",
            error
        );

    }

}


// ========================================
// COPY FOTO
// ========================================

async function copyFotoGame(img, button, id) {

    if (
        !navigator.clipboard ||
        typeof ClipboardItem === "undefined"
    ) {

        console.error(
            "❌ Browser tidak mendukung copy foto"
        );

        return;

    }

    let blob = fotoCache[id];

    // Kalau cache belum siap, buat langsung
    if (!blob) {

        if (
            !img ||
            !img.complete ||
            !img.naturalWidth
        ) {

            console.error(
                "❌ FOTO BELUM SIAP"
            );

            return;

        }

        const canvas =
            document.createElement("canvas");

        canvas.width =
            img.naturalWidth;

        canvas.height =
            img.naturalHeight;

        const ctx =
            canvas.getContext("2d");

        ctx.drawImage(
            img,
            0,
            0
        );

        blob = await new Promise(
            resolve => {

                canvas.toBlob(
                    resolve,
                    "image/png"
                );

            }
        );

    }

    if (!blob) {

        console.error(
            "❌ FOTO TIDAK BISA DIBUAT"
        );

        return;

    }

    try {

        await navigator.clipboard.write([

            new ClipboardItem({

                "image/png": blob

            })

        ]);

        console.log(
            "✅ FOTO GAME " +
            id +
            " BERHASIL DICOPY"
        );

        if (button) {

            const oldText =
                button.innerHTML;

            button.innerHTML =
                "📸 COPIED ✔";

            button.disabled = true;

            setTimeout(() => {

                button.innerHTML =
                    oldText;

                button.disabled =
                    false;

            }, 800);

        }

    } catch (error) {

        console.error(
            "❌ COPY FOTO GAGAL:",
            error
        );

    }

}


// ========================================
// POLA GAME
// KLIK = COPY FOTO
// ========================================

function polaGame(id, button) {

    const gameBox =
        button.closest(".game-box");

    if (!gameBox) return;

    const img =
        gameBox.querySelector(
            ".game-image"
        );

    if (!img) return;

    copyFotoGame(
        img,
        button,
        id
    );

}


// ========================================
// CARI FOTO
// ========================================

function cariFoto(i, img) {

    const daftarFoto = [

        `./game${i}.jpg`,
        `./game${i}.jpeg`,
        `./game${i}.png`,
        `./game${i}.webp`,

        `./Game${i}.jpg`,
        `./Game${i}.jpeg`,
        `./Game${i}.png`,
        `./Game${i}.webp`,

        `./GAME${i}.jpg`,
        `./GAME${i}.jpeg`,
        `./GAME${i}.png`,
        `./GAME${i}.webp`

    ];

    let index = 0;

    function cobaFoto() {

        if (
            index >=
            daftarFoto.length
        ) {

            console.error(
                "❌ FOTO GAME " +
                i +
                " TIDAK DITEMUKAN"
            );

            return;

        }

        const path =
            daftarFoto[index];

        img.onload = function () {

            console.log(
                "✅ FOTO GAME " +
                i +
                " SIAP"
            );

            // Cache foto segera setelah dimuat
            siapkanFoto(
                img,
                i
            );

        };

        img.onerror = function () {

            index++;

            cobaFoto();

        };

        img.src = path;

    }

    cobaFoto();

}


